export function ImgIcon({
  src,
  alt = "",
  className,
  invert,
}: {
  src: string;
  alt?: string;
  className?: string;
  invert?: boolean;
}) {
  return (
    <img
      src={src}
      alt={alt}
      className={className}
      draggable={false}
      style={invert ? { filter: "brightness(0) invert(1)" } : undefined}
    />
  );
}

export function TabMaskIcon({ src, active }: { src: string; active?: boolean }) {
  return (
    <span
      aria-hidden
      className="block h-6 w-6"
      style={{
        backgroundColor: active ? "#f95959" : "#768096",
        WebkitMaskImage: `url(${src})`,
        maskImage: `url(${src})`,
        WebkitMaskRepeat: "no-repeat",
        maskRepeat: "no-repeat",
        WebkitMaskPosition: "center",
        maskPosition: "center",
        WebkitMaskSize: "contain",
        maskSize: "contain",
      }}
    />
  );
}
